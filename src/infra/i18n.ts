const TABLES: Record<Lang, Record<Key, string>> = { es, en };
let lang: Lang = 'es';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}
export function getLang(): Lang { return lang; }

export function t(k: Key, params: Record<string, string | number> = {}): string {
  let s = TABLES[lang][k] ?? k;
  for (const [p, v] of Object.entries(params)) s = s.replace(`{${p}}`, String(v));
  return s;
}
export type I18nKey = Key;
